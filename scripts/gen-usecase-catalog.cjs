// Generates src/lib/usecases/catalog.ts: a light index (slug, industry, title, summary, tags) so the console can list use cases without loading the articles.
const path=require("path"),fs=require("fs");
const UI=process.env.UI_DIR||path.resolve(__dirname,"..");
const root=UI+"/src";
const sucrase=require(UI+"/node_modules/sucrase");
const Module=require("module");
const orig=Module._resolveFilename;
Module._resolveFilename=function(req,...a){ if(req.startsWith("@/")) req=path.join(root,req.slice(2)); return orig.call(this,req,...a); };
const origLoad=Module._load;
Module._load=function(req,parent,...r){ if(req==="lucide-react"||req.startsWith("simple-icons")) return new Proxy({}, {get:(_,k)=>k==="__esModule"?false:(()=>null)}); return origLoad.call(this,req,parent,...r); };
for(const ext of [".ts",".tsx"]) require.extensions[ext]=(m,f)=>{ m._compile(sucrase.transform(fs.readFileSync(f,"utf8"),{transforms:["typescript","imports","jsx"],filePath:f}).code,f); };
const {USE_CASES}=require(root+"/lib/usecases/index.ts");
const {PIPELINES}=require(root+"/lib/usecases/pipelines.ts");
const rows=USE_CASES.map(u=>({slug:u.slug,industry:u.industry,title:u.title,summary:u.summary,tags:u.tags,hasPipeline:!!PIPELINES[u.slug]}));
const out=`// Generated by scripts/gen-usecase-catalog.cjs. Do not edit by hand.\nexport type UseCaseEntry = { slug: string; industry: string; title: string; summary: string; tags: string[]; hasPipeline: boolean };\nexport const USE_CASE_CATALOG: UseCaseEntry[] = ${JSON.stringify(rows,null,2)};\n`;
fs.writeFileSync(root+"/lib/usecases/catalog.ts",out);
console.log("wrote",rows.length,"entries;",rows.filter(r=>r.hasPipeline).length,"with pipelines");
const missing=Object.keys(PIPELINES).filter(s=>!USE_CASES.find(u=>u.slug===s)); if(missing.length) console.log("PIPELINES WITHOUT ARTICLE",missing);
