import { decide, validateGrant, newKey, type Grant } from "../src/lib/mlops/mcp-access";
import { seedServers } from "../src/lib/mlops/mcp-seeds";
let f = 0; const t = (n: string, c: boolean) => { if (!c) { f++; console.error("FAIL", n); } };
const srv = seedServers()[0]; const read = srv.tools.find((x) => x.effect === "reads")!; const chg = srv.tools.find((x) => x.effect === "changes")!;
const P = { kind: "user" as const, id: "u1", label: "U" };
const g = (o: Partial<Grant>): Grant => ({ id: "g", serverId: srv.id, principal: P, tools: "all", scope: "reads", ratePerMinute: 60, note: "n", createdBy: "x", createdAt: "", status: "active", ...o });
const now = Date.parse("2026-11-02T00:00:00Z");
t("closed by default", decide([], srv.id, "u1", read, now).code === "no-grant");
t("reads allowed", decide([g({})], srv.id, "u1", read, now).allowed);
t("changes need scope", decide([g({})], srv.id, "u1", chg, now).code === "needs-changes-scope");
t("changes allowed with scope and approval flag", (() => { const v = decide([g({ scope: "changes" })], srv.id, "u1", chg, now); return v.allowed && v.needsApproval === chg.approval; })());
t("tool subset", decide([g({ tools: [chg.id] , scope: "changes"})], srv.id, "u1", read, now).code === "tool-not-covered");
t("expired", decide([g({ expiresAt: "2026-10-01T00:00:00Z" })], srv.id, "u1", read, now).code === "expired");
t("revoked", decide([g({ status: "revoked" })], srv.id, "u1", read, now).code === "revoked");
t("other server", decide([g({ serverId: "other" })], srv.id, "u1", read, now).code === "no-grant");
t("broader grant not hidden", decide([g({ tools: [chg.id], scope: "changes" }), g({ id: "g2" })], srv.id, "u1", read, now).allowed);
t("unknown tool", decide([g({})], srv.id, "u1", undefined, now).code === "unknown-tool");
const base = { serverId: srv.id, principal: P, tools: "all" as const, scope: "reads" as const, ratePerMinute: 60, expiresInDays: 30, note: "Support copilot needs lookups" };
t("valid", validateGrant(base, srv, []) === null);
t("rate above server", !!validateGrant({ ...base, ratePerMinute: srv.ratePerMinute + 1 }, srv, []));
t("empty note", !!validateGrant({ ...base, note: "x" }, srv, []));
t("no tools", !!validateGrant({ ...base, tools: [] }, srv, []));
t("changes scope without changing tool", !!validateGrant({ ...base, scope: "changes", tools: [read.id] }, srv, []));
t("group all-changes refused", !!validateGrant({ ...base, scope: "changes", principal: { kind: "group", id: "g", label: "g" } }, srv, []));
t("duplicate active", !!validateGrant(base, srv, [g({})]));
t("auth none", !!validateGrant(base, { ...srv, auth: "none" }, []));
const k = newKey(); t("key shape", /^tok_mcp_[a-z0-9]{40}$/.test(k.value) && k.value.startsWith(k.prefix));
console.log(f ? `${f} failed` : "mcp-access: all checks passed"); process.exit(f ? 1 : 0);
