// Generates src/lib/icons/brand-icons.generated.ts from the installed simple-icons package.
// Only the listed brands are imported by name, so the bundle carries these icons and not the whole package.
// Run: node scripts/gen-icon-collection.cjs   (re-run after changing the list or upgrading simple-icons)
const fs = require("fs");
const path = require("path");
const si = require("simple-icons");

const GROUPS = {
  "Cloud and hosting": "amazonwebservices googlecloud cloudflare digitalocean hetzner vultr ovh scaleway openstack vmware oracle snowflake databricks",
  "Containers and infrastructure": "kubernetes docker podman helm flux terraform ansible pulumi rancher nomad linux ubuntu redhat debian nvidia intel amd arm",
  "AWS services": "amazons3 amazonec2 amazondynamodb amazonrds amazoneks amazonecs awslambda amazoncloudwatch amazonsqs",
  "Google Cloud services": "googlecloudstorage googlebigquery",
  "Machine learning and AI": "huggingface pytorch tensorflow onnx scikitlearn keras mlflow bentoml ray apachespark apacheairflow prefect dbt jupyter pandas numpy openai anthropic meta googlegemini ollama langchain",
  "Databases and storage": "postgresql mysql mariadb mongodb redis sqlite clickhouse cockroachlabs elasticsearch opensearch apachecassandra neo4j minio ceph milvus",
  "Streaming and messaging systems": "apachekafka rabbitmq apachepulsar",
  "Observability": "prometheus grafana opentelemetry datadog newrelic splunk sentry elastic jaeger dynatrace pagerduty opsgenie",
  "Source, build and registry": "github gitlab bitbucket gitea jenkins circleci githubactions harbor sonatype jfrog snyk trivy",
  "Payments and money": "stripe paypal adyen bitcoin ethereum visa mastercard orange airtel vodafone",
  "Email, chat and calendar": "twilio sendgrid mailgun gmail protonmail slack discord telegram whatsapp signal zoom googlecalendar googledrive dropbox box notion jira confluence linear asana trello zapier",
  "Identity and security": "okta auth0 keycloak vault hashicorp 1password bitwarden letsencrypt openid",
  "APIs and languages": "graphql swagger openapiinitiative postman json yaml python typescript go rust nodedotjs spring springboot apachemaven gradle",
};

const rows = [];
const imports = [];
for (const [group, list] of Object.entries(GROUPS)) {
  for (const slug of list.split(/\s+/)) {
    const key = "si" + slug[0].toUpperCase() + slug.slice(1);
    if (!si[key]) throw new Error("simple-icons has no " + key + ". Remove " + slug + " from the list.");
    imports.push(key);
    rows.push({ id: "si-" + slug, key, group, title: si[key].title });
  }
}
const out = [];
out.push("// GENERATED by scripts/gen-icon-collection.cjs. Do not edit by hand.");
out.push("import {");
for (let i = 0; i < imports.length; i += 8) out.push("  " + imports.slice(i, i + 8).join(", ") + ",");
out.push('} from "simple-icons";');
out.push("");
out.push("export type BrandIcon = { id: string; title: string; group: string; path: string; hex: string };");
out.push("");
out.push("export const BRAND_ICONS: BrandIcon[] = [");
for (const r of rows) out.push(`  { id: ${JSON.stringify(r.id)}, title: ${JSON.stringify(r.title)}, group: ${JSON.stringify(r.group)}, path: ${r.key}.path, hex: ${r.key}.hex },`);
out.push("];");
out.push("");
fs.writeFileSync(path.join(__dirname, "..", "src", "lib", "icons", "brand-icons.generated.ts"), out.join("\n"));
console.log("wrote", rows.length, "brand icons");
